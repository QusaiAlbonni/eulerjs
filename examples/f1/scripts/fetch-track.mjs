// Fetches Monza's Grand Prix circuit from OpenStreetMap and writes it, in metres, to
// src/track/monza.ts: the racing line's ways chained in driving order, the pit lane, and the
// start. Run it again to pick up changes to the map:
//
//   node examples/f1/scripts/fetch-track.mjs
//
// The map's data is © OpenStreetMap contributors, under the Open Database License, and so is the
// file this writes: https://www.openstreetmap.org/copyright
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** Autodromo Nazionale di Monza, the circuit relation. */
const RELATION = 284565;
const OVERPASS = 'https://overpass-api.de/api/interpreter';
const EARTH_RADIUS = 6_378_137;

const response = await fetch(OVERPASS, {
  method: 'POST',
  headers: { 'User-Agent': 'eulerjs-f1-example (https://github.com/QusaiAlbonni/eulerjs)', 'Content-Type': 'application/x-www-form-urlencoded' },
  body: new URLSearchParams({ data: `[out:json][timeout:60];relation(${RELATION});out geom;` }),
});
if (!response.ok) throw new Error(`OpenStreetMap's Overpass API answered ${response.status}`);
const relation = (await response.json()).elements[0];

const ways = relation.members.filter((member) => member.type === 'way' && member.role !== 'pit_lane').map((member) => member.geometry);
const pitLane = relation.members.find((member) => member.role === 'pit_lane')?.geometry ?? [];
const startNode = relation.members.find((member) => member.type === 'node' && member.role === 'start');

// the ways run in driving order, each starting where another ends: chain them
const same = (first, second) => Math.abs(first.lat - second.lat) < 1e-9 && Math.abs(first.lon - second.lon) < 1e-9;
const lap = [...ways[0]];
const left = ways.slice(1);
while (left.length > 0) {
  const next = left.findIndex((way) => same(way[0], lap[lap.length - 1]));
  if (next < 0) throw new Error(`the circuit's ways don't join up: ${left.length} left over`);
  lap.push(...left.splice(next, 1)[0].slice(1));
}
if (same(lap[0], lap[lap.length - 1])) lap.pop();

// metres east and north of the circuit's middle, flat: a few kilometres across, the earth's curve is a millimetre or so
const middle = lap.reduce((sum, point) => ({ lat: sum.lat + point.lat / lap.length, lon: sum.lon + point.lon / lap.length }), { lat: 0, lon: 0 });
const toMetres = (point) => [
  Math.round(((point.lon - middle.lon) * Math.PI) / 180 * EARTH_RADIUS * Math.cos((middle.lat * Math.PI) / 180) * 100) / 100,
  Math.round(((point.lat - middle.lat) * Math.PI) / 180 * EARTH_RADIUS * 100) / 100,
];
const length = lap.reduce((sum, point, index) => {
  const [east, north] = toMetres(point);
  const [nextEast, nextNorth] = toMetres(lap[(index + 1) % lap.length]);
  return sum + Math.hypot(nextEast - east, nextNorth - north);
}, 0);

const list = (points) => points.map((point) => `[${toMetres(point).join(', ')}]`).join(', ');
const source = `// Generated by scripts/fetch-track.mjs from OpenStreetMap, relation ${RELATION}: do not edit.
// © OpenStreetMap contributors. This data is available under the Open Database License (ODbL):
// https://www.openstreetmap.org/copyright

/** Monza's Grand Prix circuit, in metres east and north of its middle (${middle.lat.toFixed(5)}° N, ${middle.lon.toFixed(5)}° E). */
export const MONZA = {
  name: 'Monza',
  /** Round the lap's centre line, in driving order: ${(length / 1000).toFixed(3)} km. */
  centreLine: [${list(lap)}] as [number, number][],
  pitLane: [${list(pitLane)}] as [number, number][],
  start: [${startNode ? toMetres(startNode).join(', ') : toMetres(lap[0]).join(', ')}] as [number, number],
};
`;
const out = fileURLToPath(new URL('../src/track/monza.ts', import.meta.url));
writeFileSync(out, source);
console.log(`${lap.length} points round the lap, ${(length / 1000).toFixed(3)} km, written to ${out}`);
